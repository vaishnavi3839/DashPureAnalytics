-- Latest state of each report, and orphaned reports sorted by cost.

CREATE OR REPLACE VIEW RPT_CURRENT_STATE AS
WITH latest AS (
    SELECT *
    FROM STG_REPORT_USAGE
    QUALIFY ROW_NUMBER() OVER (PARTITION BY REPORT_ID ORDER BY SNAPSHOT_SEQ DESC) = 1
),
last_known_owner AS (
    -- last owner we know of, a good person to hand an orphaned report back to
    SELECT REPORT_ID, OWNER_EMAIL AS LAST_KNOWN_OWNER
    FROM STG_REPORT_USAGE
    WHERE OWNER_EMAIL IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY REPORT_ID ORDER BY SNAPSHOT_SEQ DESC) = 1
),
health AS (
    SELECT
        REPORT_ID,
        ROUND(AVG(AVG_LOAD_TIME_SEC), 1)                                                   AS AVG_LOAD_TIME_SEC,
        MAX(AVG_LOAD_TIME_SEC)                                                             AS MAX_LOAD_TIME_SEC,
        SUM(CASE WHEN IS_LATENCY_BREACH THEN 1 ELSE 0 END)                                 AS LATENCY_BREACHES,
        ROUND(SUM(CASE WHEN IS_REFRESH_FAILURE THEN 1 ELSE 0 END) * 1.0
              / NULLIF(SUM(CASE WHEN LAST_REFRESH_STATUS <> 'UNKNOWN' THEN 1 ELSE 0 END), 0), 3) AS REFRESH_FAILURE_RATE,
        SUM(CASE WHEN IS_ORPHANED THEN 1 ELSE 0 END)                                       AS ORPHANED_SNAPSHOTS
    FROM STG_REPORT_USAGE
    GROUP BY REPORT_ID
)
SELECT
    l.REPORT_ID,
    l.REPORT_NAME,
    l.OWNER_EMAIL                AS CURRENT_OWNER,
    l.IS_ORPHANED,
    k.LAST_KNOWN_OWNER,
    l.LAST_REFRESH_STATUS,
    l.AVG_LOAD_TIME_SEC          AS LATEST_LOAD_TIME_SEC,
    l.LATENCY_BAND               AS LATEST_LATENCY_BAND,
    h.AVG_LOAD_TIME_SEC,
    h.MAX_LOAD_TIME_SEC,
    h.LATENCY_BREACHES,
    h.REFRESH_FAILURE_RATE,
    h.ORPHANED_SNAPSHOTS,
    u.TOTAL_COST_USD,
    u.TOTAL_COST_PER_VIEW
FROM latest l
JOIN health h               ON h.REPORT_ID = l.REPORT_ID
JOIN RPT_UNIT_COST u        ON u.REPORT_ID = l.REPORT_ID
LEFT JOIN last_known_owner k ON k.REPORT_ID = l.REPORT_ID;

-- orphaned reports, most expensive first
SELECT REPORT_ID, REPORT_NAME, LAST_KNOWN_OWNER, LAST_REFRESH_STATUS, LATEST_LOAD_TIME_SEC,
       REFRESH_FAILURE_RATE, TOTAL_COST_USD, TOTAL_COST_PER_VIEW
FROM RPT_CURRENT_STATE
WHERE IS_ORPHANED
ORDER BY TOTAL_COST_USD DESC;
