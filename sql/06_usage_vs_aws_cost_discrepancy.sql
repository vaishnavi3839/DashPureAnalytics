-- Does AWS hosting cost follow usage? Correlation, outliers and the list of odd reports.

SELECT
    ROUND(CORR(MONTHLY_ACTIVE_VIEWS, AWS_HOSTING_COST_USD), 3)     AS CORR_VIEWS_VS_AWS_COST,
    ROUND(CORR(MONTHLY_ACTIVE_VIEWS, SNOWFLAKE_CREDITS_VALID), 3)  AS CORR_VIEWS_VS_CREDITS,
    COUNT(*)                                                       AS ROWS_USED
FROM STG_REPORT_USAGE
WHERE MONTHLY_ACTIVE_VIEWS > 0;

-- snapshots where AWS cost per view is an outlier (above Q3 + 1.5 x IQR)
CREATE OR REPLACE VIEW AWS_COST_OUTLIER_SNAPSHOTS AS
WITH k AS (SELECT CONFIG_VALUE AS IQR_K FROM COST_CONFIG WHERE CONFIG_KEY = 'OUTLIER_IQR_K'),
fence AS (
    SELECT
        PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY AWS_COST_PER_VIEW) AS Q1,
        PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY AWS_COST_PER_VIEW) AS Q3
    FROM STG_REPORT_USAGE
    WHERE AWS_COST_PER_VIEW IS NOT NULL
)
SELECT
    s.SOURCE_ROW_NUMBER,
    s.REPORT_ID,
    s.SNAPSHOT_SEQ,
    s.MONTHLY_ACTIVE_VIEWS,
    s.AWS_HOSTING_COST_USD,
    ROUND(s.AWS_COST_PER_VIEW, 2)                       AS AWS_COST_PER_VIEW,
    ROUND(f.Q3 + k.IQR_K * (f.Q3 - f.Q1), 4)            AS FENCE
FROM STG_REPORT_USAGE s
CROSS JOIN fence f
CROSS JOIN k
WHERE s.AWS_COST_PER_VIEW > f.Q3 + k.IQR_K * (f.Q3 - f.Q1);

-- reports to look at: above the fence, outlier in 5+ of 20 snapshots, or cost with zero views
CREATE OR REPLACE VIEW RPT_AWS_COST_DISCREPANCY AS
WITH k AS (SELECT CONFIG_VALUE AS IQR_K FROM COST_CONFIG WHERE CONFIG_KEY = 'OUTLIER_IQR_K'),
report_rates AS (
    SELECT
        REPORT_ID,
        SUM(MONTHLY_ACTIVE_VIEWS)                                        AS TOTAL_VIEWS,
        SUM(AWS_HOSTING_COST_USD)                                        AS AWS_COST_USD,
        SUM(AWS_HOSTING_COST_USD) / NULLIF(SUM(MONTHLY_ACTIVE_VIEWS), 0) AS AWS_PER_VIEW,
        SUM(CASE WHEN IS_ZERO_VIEW_WITH_COST THEN 1 ELSE 0 END)          AS ZERO_VIEW_SNAPSHOTS
    FROM STG_REPORT_USAGE
    GROUP BY REPORT_ID
),
report_fence AS (
    SELECT
        PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY AWS_PER_VIEW) AS Q1,
        PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY AWS_PER_VIEW) AS Q3
    FROM report_rates
),
outlier_counts AS (
    SELECT REPORT_ID, COUNT(*) AS OUTLIER_SNAPSHOTS
    FROM AWS_COST_OUTLIER_SNAPSHOTS
    GROUP BY REPORT_ID
)
SELECT
    r.REPORT_ID,
    r.TOTAL_VIEWS,
    ROUND(r.AWS_COST_USD, 2)                                     AS AWS_HOSTING_COST_USD,
    ROUND(r.AWS_PER_VIEW, 4)                                     AS AWS_COST_PER_VIEW,
    ROUND(f.Q3 + k.IQR_K * (f.Q3 - f.Q1), 4)                     AS REPORT_FENCE,
    COALESCE(o.OUTLIER_SNAPSHOTS, 0)                             AS OUTLIER_SNAPSHOTS,
    r.ZERO_VIEW_SNAPSHOTS,
    CASE WHEN r.AWS_PER_VIEW > f.Q3 + k.IQR_K * (f.Q3 - f.Q1) THEN TRUE ELSE FALSE END AS ABOVE_REPORT_FENCE,
    CASE WHEN COALESCE(o.OUTLIER_SNAPSHOTS, 0) >= 5           THEN TRUE ELSE FALSE END AS PERSISTENT_OUTLIER
FROM report_rates r
CROSS JOIN report_fence f
CROSS JOIN k
LEFT JOIN outlier_counts o ON o.REPORT_ID = r.REPORT_ID
WHERE r.AWS_PER_VIEW > f.Q3 + k.IQR_K * (f.Q3 - f.Q1)
   OR COALESCE(o.OUTLIER_SNAPSHOTS, 0) >= 5
   OR r.ZERO_VIEW_SNAPSHOTS > 0;

SELECT * FROM RPT_AWS_COST_DISCREPANCY ORDER BY AWS_COST_PER_VIEW DESC;

-- worst 10 snapshots
SELECT * FROM AWS_COST_OUTLIER_SNAPSHOTS ORDER BY AWS_COST_PER_VIEW DESC LIMIT 10;
